// node tools/debuffs.js <folder with SpellCategories.csv SpellName.csv SpellEffect.csv> → addon/ForeverCleanse/Debuffs.lua
// The CSVs come from https://wago.tools/db2/<table>/csv?build=1.60.1.70959 (the WoW: Forever build).
// Keeps spells with a dispel type (Magic, Curse, Disease, Poison) that put an aura on an enemy: the debuffs players get.
const fs = require('fs'), path = require('path');
const dir = process.argv[2];
if (!dir) { console.error('usage: node tools/debuffs.js <csv folder>'); process.exit(1); }

function csv(name) {
  const text = fs.readFileSync(path.join(dir, name + '.csv'), 'utf8');
  const rows = [];
  let row = [], cell = '', q = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (q) { if (ch === '"') { if (text[i + 1] === '"') { cell += '"'; i++ } else q = false } else cell += ch; continue }
    if (ch === '"') q = true;
    else if (ch === ',') { row.push(cell); cell = '' }
    else if (ch === '\n') { row.push(cell.replace(/\r$/, '')); rows.push(row); row = []; cell = '' }
    else cell += ch;
  }
  if (cell || row.length) { row.push(cell); rows.push(row) }
  const head = rows.shift();
  return rows.filter(r => r.length === head.length).map(r => Object.fromEntries(head.map((h, i) => [h, r[i]])));
}

const TYPES = { 1: 'Magic', 2: 'Curse', 3: 'Disease', 4: 'Poison' };
// aura on an enemy unit or enemy area (target ids from the game's ImplicitTarget enum)
const ENEMY = new Set([6, 8, 15, 16, 24, 28, 53, 54, 77, 104, 110, 111]);
const AURA = new Set([6, 27, 128, 129]); // apply aura, persistent area aura, area auras

const dispel = new Map();
for (const r of csv('SpellCategories')) if (TYPES[r.DispelType] && r.DifficultyID === '0') dispel.set(+r.SpellID, TYPES[r.DispelType]);
const hostile = new Set();
for (const r of csv('SpellEffect')) {
  if (AURA.has(+r.Effect) && (ENEMY.has(+r.ImplicitTarget_0) || ENEMY.has(+r.ImplicitTarget_1))) hostile.add(+r.SpellID);
}
const names = new Map(csv('SpellName').map(r => [+r.ID, r.Name_lang]));

// one entry per type + name, with every id that carries that name
const out = { Curse: new Map(), Poison: new Map(), Disease: new Map(), Magic: new Map() };
for (const [id, type] of dispel) {
  const name = names.get(id);
  if (!hostile.has(id) || !name || /^(zz|z|test|dnd|unused|qa)\b|\(old\)|deprecated|\[dnd\]/i.test(name)) continue;
  const m = out[type];
  if (!m.has(name)) m.set(name, []);
  m.get(name).push(id);
}

const lua = ['-- generated by tools/debuffs.js from the WoW: Forever spell tables (build 1.60.1.70959): do not edit',
  '-- every debuff a player can get, by dispel type: { name, id, id, ... }', 'local _, ns = ...', 'ns.DEBUFFS = {'];
let total = 0;
for (const type of Object.keys(out)) {
  const list = [...out[type]].sort((a, b) => a[0].localeCompare(b[0]));
  total += list.length;
  lua.push(`  ${type} = {`);
  for (const [name, ids] of list) lua.push(`    { ${JSON.stringify(name)}, ${ids.sort((a, b) => a - b).join(', ')} },`);
  lua.push('  },');
  console.log(type, list.length);
}
lua.push('}', '');
fs.writeFileSync(path.join(__dirname, '../addon/ForeverCleanse/Debuffs.lua'), lua.join('\n'));
console.log('total', total);
